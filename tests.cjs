"use strict";
const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const sandbox = { module: { exports: {} }, require: name => {
  if (name === "obsidian") return { Plugin: class {}, PluginSettingTab: class {}, MarkdownRenderChild: class {} };
  if (name === "@codemirror/view") return { WidgetType: class {} };
  if (name === "@codemirror/language") return {};
  if (name === "@codemirror/state") return {};
  if (name === "./folding.js") return require("./folding.js");
  if (name === "./formatting.js") return require("./formatting.js");
  throw new Error(name);
} };
vm.runInNewContext(fs.readFileSync(`${__dirname}/main-source.js`, "utf8"), sandbox);
const { parseOptions, indentColumns } = sandbox.module.exports;
assert.equal(typeof parseOptions, "function");
assert.equal(Object.hasOwn(parseOptions('java title="Employee Server.java"'), "title"), false);
assert.equal(Object.hasOwn(parseOptions("python ln=false start=20"), "numbers"), false);
assert.equal(Object.hasOwn(parseOptions("python ln start=20"), "numbers"), false);
assert.equal(Object.hasOwn(parseOptions("text start=0"), "start"), false);
assert.equal(Object.hasOwn(parseOptions("text start=NaN"), "start"), false);
assert.equal(Object.hasOwn(parseOptions('js filename="main.js"'), "title"), false);
assert.equal(Object.hasOwn(parseOptions('java file="Main.java"'), "title"), false);
assert.equal(parseOptions("java filename:'hello world.java' ln:12").language, "java");
assert.equal(indentColumns(" \tcode", 4), 4);
assert.equal(indentColumns("\t\tcode", 4), 8);
const { foldRegions } = require("./folding.js");
const java = 'class Demo {\n  void run() {\n    String s = "{ fake }";\n    // } not a closing brace\n    if (true) {\n      call();\n    }\n  }\n}';
assert.equal(foldRegions(java, "java").length, 3);
assert.equal(foldRegions('def run():\n    if True:\n        print("hello")\n    return 1\n', "python").length, 2);
assert.equal(foldRegions('const text = "{\\n}";\n', "javascript").length, 0);
assert.equal(foldRegions('<section>\n<p>test</p>\n</section>', "html").length, 1);
assert.equal(foldRegions('a {\n  color: red;\n}', "css").length, 1);
assert.equal(foldRegions('plain\ntext', "text").length, 0);
assert.equal(foldRegions('#include <stdio.h>\nint main(void) {\n  const char *s = "}";\n  if (1) {\n    puts(s);\n  }\n}', "c").length, 2);
assert.equal(foldRegions('template<class T>\nclass Box {\n  void run() {\n    // { fake\n    call();\n  }\n};', "cpp").length, 2);
assert.equal(foldRegions('package main\nfunc main() {\n  s := `}`\n  if true {\n    println(s)\n  }\n}', "go").length, 2);
assert.equal(foldRegions('fn main() {\n  let s = r#"}"#;\n  if true {\n    println!("{}", s);\n  }\n}', "rust").length, 2);
console.log("20 assertions passed");
